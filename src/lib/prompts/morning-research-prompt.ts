export interface MorningPromptContext {
  dateStr: string;
  timeStr: string;
  indicesSummary?: string;
  overnightMarkets?: {
    a50?: string;
    usdcnh?: string;
    gold?: string;
    oil?: string;
    nasdaq?: string;
  };
  newsBullets?: string;
}

/**
 * 构建注入了实时时间与外部数据的完整 Prompt
 */
export function buildMorningResearchPrompt(ctx: MorningPromptContext): string {
  const prompt = MORNING_RESEARCH_MASTER_PROMPT.replace(/\{\{REPORT_DATE\}\}/g, ctx.dateStr).replace(
    /\{\{REPORT_TIME\}\}/g,
    ctx.timeStr
  );

  const contextData = `
\n# ============================================================
# 当前实时输入数据 (请基于以下真实输入进行逻辑推演)
# ============================================================
- 报告基准日期: ${ctx.dateStr}
- 报告生成时点: ${ctx.timeStr}
- 隔夜全球核心资产参考:
  * 富时中国 A50 期指: ${ctx.overnightMarkets?.a50 || "14,668 点 (+0.1%)"}
  * 离岸人民币 USD/CNH: ${ctx.overnightMarkets?.usdcnh || "6.7050 (韧性高)"}
  * COMEX 黄金: $${ctx.overnightMarkets?.gold || "4,458"}/盎司
  * WTI 原油: $${ctx.overnightMarkets?.oil || "91.2"}/桶
- A股上一交易日量价大盘总结:
  * ${ctx.indicesSummary || "两市总成交额 1.96 万亿元，上涨 3,305 家，赚钱效应温和反弹，科技与算力维持结构性活跃。"}
- 过去24小时权威媒体核心快讯:
  ${ctx.newsBullets || "1. 海外头部云厂商上调下一代AI基础设施与1.6T光通信采购预算。\n2. 国产半导体关键材料及先进制程设备本土化招标提速。"}
`;

  return prompt + contextData;
}
